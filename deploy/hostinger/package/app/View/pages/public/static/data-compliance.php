                <h2>1. Our Compliance Commitment</h2>
                <p>We maintain a documented compliance programme covering:</p>
                <ul>
                    <li>Data protection governance, with defined roles and accountability.</li>
                    <li>Lawful and proportionate collection of personal data, limited to what is necessary.</li>
                    <li>Secure processing, storage, and transmission of personal data.</li>
                    <li>Transparent privacy notices available wherever personal data is collected.</li>
                    <li>Regular staff awareness and data handling training.</li>
                    <li>Vendor and processor due diligence through data processing agreements.</li>
                    <li>Routine audits, incident response, and continuous improvement.</li>
                </ul>

                <h2>2. Regulatory Framework</h2>
                <p>Our data practices are aligned with the following frameworks and instruments:</p>
                <ul>
                    <li><strong>Nigeria Data Protection Act, 2023</strong> and the Nigeria Data Protection Regulation (NDPR) — the primary framework for processing personal data in Nigeria.</li>
                    <li><strong>GDPR (EU) 2016/679</strong> — where we process the personal data of individuals located in the EEA.</li>
                    <li><strong>Nigeria's Cybercrime (Prohibition, Prevention, Etc.) Act</strong> — informing our information security safeguards.</li>
                    <li><strong>Consumer protection law</strong> — governing fair trading, product quality, and customer redress.</li>
                    <li><strong>Anti-money laundering and know-your-customer expectations</strong> — applied to business relationships where relevant.</li>
                </ul>

                <h2>3. Categories of Data We Process</h2>
                <p>We process the following categories of personal data, each for identified purposes described in our <a href="<?= app_url('/privacy-policy') ?>">Privacy Policy</a>:</p>
                <ul>
                    <li>Identity, contact, and company information of customers and prospects.</li>
                    <li>Order, quotation, and transaction records.</li>
                    <li>Account credentials and communication preferences.</li>
                    <li>Technical usage data collected through cookies and analytics.</li>
                    <li>Communications and support correspondence.</li>
                </ul>
                <p>We do not intentionally collect special category (sensitive) data, and we never collect more data than is necessary for the stated purpose.</p>

                <h2>4. Lawful Bases for Processing</h2>
                <p>Where required, each processing activity is grounded in at least one lawful basis:</p>
                <ul>
                    <li><strong>Contract</strong> — performing orders, quotes, and agreed services.</li>
                    <li><strong>Legal obligation</strong> — tax, accounting, and regulatory record-keeping.</li>
                    <li><strong>Legitimate interests</strong> — security, fraud prevention, and service improvement, balanced against your rights.</li>
                    <li><strong>Consent</strong> — marketing and optional analytics, withdrawable at any time.</li>
                </ul>

                <h2>5. Data Protection Principles</h2>
                <p>Our processing activities adhere to the core data protection principles:</p>
                <ul>
                    <li><strong>Lawfulness, fairness, and transparency</strong> — we process data openly and as described in our policies.</li>
                    <li><strong>Purpose limitation</strong> — data is collected for specified, explicit, and legitimate purposes only.</li>
                    <li><strong>Data minimisation</strong> — we limit collection to what is relevant and necessary.</li>
                    <li><strong>Accuracy</strong> — we take reasonable steps to keep data accurate and up to date.</li>
                    <li><strong>Storage limitation</strong> — data is retained only as long as necessary.</li>
                    <li><strong>Integrity and confidentiality</strong> — data is protected with appropriate security measures.</li>
                    <li><strong>Accountability</strong> — we document and can demonstrate our compliance.</li>
                </ul>

                <h2>6. Data Subject Rights</h2>
                <p>You have the right to:</p>
                <ul>
                    <li>Access the personal data we hold about you.</li>
                    <li>Request correction of inaccurate or incomplete data.</li>
                    <li>Request erasure of your data, subject to legal retention obligations.</li>
                    <li>Restrict or object to certain processing.</li>
                    <li>Receive your data in a portable format where applicable.</li>
                    <li>Withdraw consent for marketing at any time.</li>
                    <li>Lodge a complaint with a supervisory authority, including the Nigeria Data Protection Commission.</li>
                </ul>
                <p>Submit requests via <a href="mailto:data@marigoldsignatureng.com">data@marigoldsignatureng.com</a>. We will acknowledge requests promptly and respond within the statutory timeframe.</p>

