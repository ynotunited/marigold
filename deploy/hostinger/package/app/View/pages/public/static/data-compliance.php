                <h2>8. Security Safeguards</h2>
                <p>We apply organisational and technical measures appropriate to the risk, including:</p>
                <ul>
                    <li>Transport Layer Security (HTTPS) for all data transmitted to our website.</li>
                    <li>Hashing and salting of passwords and security tokens.</li>
                    <li>Role-based access controls and least-privilege principles.</li>
                    <li>Input validation, output encoding, and CSRF protection across our applications.</li>
                    <li>Secure coding practices verified through regular review and testing.</li>
                    <li>Physical and logical access controls at hosting facilities.</li>
                </ul>

                <h2>9. Third-Party Processors</h2>
                <p>We engage a limited set of processors — including hosting, payment, logistics, and email providers — to deliver our services. Each processor is subject to:</p>
                <ul>
                    <li>A data processing agreement imposing the same data protection obligations.</li>
                    <li>Instructions to process data only for our documented purposes.</li>
                    <li>Reasonable security assurances and breach notification obligations.</li>
                </ul>

                <h2>10. Data Breach Management</h2>
                <p>We maintain an incident response plan for data security events. In the event of a personal data breach, we will:</p>
                <ul>
                    <li>Contain and assess the scope and risk of the breach without delay.</li>
                    <li>Notify affected individuals and the relevant supervisory authority where the breach is likely to result in risk to their rights and freedoms.</li>
                    <li>Document the breach and the corrective actions taken.</li>
                    <li>Review and strengthen safeguards to prevent recurrence.</li>
                </ul>

                <h2>11. Compliance &amp; Oversight</h2>
                <p>Compliance is overseen by our designated data protection contact, who monitors regulatory developments, coordinates data subject requests, reviews processing activities, and reports on compliance to management. Our policies are reviewed at least annually and whenever significant changes occur in our operations or applicable law.</p>

