                <h2>1. Respect for Intellectual Property</h2>
                <p>All content on our website — including text, graphics, logos, product photography, designs, software, and code — is protected by copyright, trademark, and other intellectual property laws. We expect our clients to hold or be authorised to use any artwork, logos, or designs they submit for customisation. We may refuse or discontinue production of any order that we reasonably believe infringes third-party rights.</p>

                <h2>2. Copyright Infringement Notices</h2>
                <p>If you believe that content on our website infringes a copyright you own or control, you may submit a takedown notice. Your notice must be sent to our designated contact and must include the information listed in Section 4 below.</p>
                <p>Upon receiving a complete and valid notice, we will review the claim, remove or disable access to the allegedly infringing content, and notify the affected party. We may forward a copy of the notice to the affected party and, where required, to the relevant authorities.</p>

                <h2>3. Trademark &amp; Design Infringement Notices</h2>
                <p>If you believe a trademark or registered design is being used without authorisation on our website or in products we produce, please submit a notice including the information in Section 4. We will investigate the claim and take appropriate action, which may include removing the content or ceasing production of the affected custom order.</p>

                <h2>4. Information Required in a Notice</h2>
                <p>To help us act quickly and accurately, every notice must include the following:</p>
                <ul>
                    <li><strong>Identification of the IP right</strong> — the specific work, trademark, or design claimed to be infringed, including registration numbers where available.</li>
                    <li><strong>Location of the infringing content</strong> — the exact URL(s) or a description sufficient to locate the content on our website or the order/product concerned.</li>
                    <li><strong>Proof of ownership or authority</strong> — a statement that you own or control the rights, or are authorised to act on behalf of the rights holder, with supporting documentation.</li>
                    <li><strong>Your contact details</strong> — full legal name, company name (if applicable), email address, postal address, and telephone number.</li>
                    <li><strong>Good faith declaration</strong> — a statement that you believe, in good faith, that the disputed use is not authorised by the rights holder, its agent, or the law.</li>
                    <li><strong>Accuracy declaration</strong> — a statement, made under penalty of perjury where applicable, that the information in the notice is accurate and that you are the rights holder or authorised to act on their behalf.</li>
                    <li><strong>Signature</strong> — a physical or electronic signature of the rights holder or authorised representative.</li>
                </ul>

