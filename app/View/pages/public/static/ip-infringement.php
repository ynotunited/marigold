                <p>
                    Marigold Signature respects the intellectual property rights of others and expects the users of our website and services
                    to do the same. This page explains how to report alleged copyright, trademark, or design infringement relating to content
                    on our website or to custom products produced for our clients. We respond to clear notices of alleged infringement
