                <h2>6. Counter-Notices</h2>
                <p>If content you posted or produced was removed or disabled as a result of a notice and you believe the removal was a mistake or misidentification, you may submit a counter-notice. The counter-notice must include:</p>
                <ul>
                    <li>Identification of the content removed or disabled and where it previously appeared.</li>
                    <li>A statement, made under penalty of perjury where applicable, that you have a good faith belief the removal was a mistake or misidentification.</li>
                    <li>Your name, address, and telephone number, and a statement consenting to the jurisdiction of the courts for your location.</li>
                    <li>Your physical or electronic signature.</li>
                </ul>
                <p>Upon receipt of a valid counter-notice, we may restore the content, subject to our legal obligations and the rights holder's ability to pursue the claim in court.</p>

                <h2>7. Repeat Infringer Policy</h2>
                <p>We maintain a policy of terminating accounts and refusing service to users who repeatedly submit or produce content that infringes the intellectual property rights of others. Factors considered include the number and severity of verified infringement claims and whether the user has made knowingly false claims.</p>

                <h2>8. Good Faith &amp; Misrepresentation</h2>
                <p>Please ensure that any notice or counter-notice you submit is accurate and made in good faith. Knowingly submitting a false or misleading claim of infringement may render you liable for damages and legal costs, including where permitted under applicable law, and we may disclose your identity to the affected party or authorities in connection with legal proceedings.</p>

