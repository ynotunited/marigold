                <li>Lawful and proportionate collection of personal data, limited to what is necessary.</li>
                <li>Secure processing, storage, and transmission of personal data.</li>
                <li>Transparent privacy notices available wherever personal data is collected.</li>
                <li>Regular staff awareness and data handling training.</li>
                <li>Vendor and processor due diligence through data processing agreements.</li>
                <li>Routine audits, incident response, and continuous improvement.</li>
            </ul>
