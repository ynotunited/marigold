        <div>
            <h2 class="text-2xl font-bold text-white mb-4">2. Regulatory Framework</h2>
            <p class="text-[var(--text-secondary)] leading-relaxed mb-4">Our data practices are aligned with the following frameworks and instruments:</p>
            <ul class="list-disc pl-6 space-y-2 text-[var(--text-secondary)] leading-relaxed">
                <li><strong class="text-white">Nigeria Data Protection Act, 2023</strong> and the Nigeria Data Protection Regulation (NDPR) — the primary framework for processing personal data in Nigeria.</li>
                <li><strong class="text-white">GDPR (EU) 2016/679</strong> — where we process the personal data of individuals located in the EEA.</li>
                <li><strong class="text-white">Nigeria's Cybercrime (Prohibition, Prevention, Etc.) Act</strong> — informing our information security safeguards.</li>
                <li><strong class="text-white">Consumer protection law</strong> — governing fair trading, product quality, and customer redress.</li>
                <li><strong class="text-white">Anti-money laundering and know-your-customer expectations</strong> — applied to business relationships where relevant.</li>
            </ul>
