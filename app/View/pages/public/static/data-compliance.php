        <div>
            <h2 class="text-2xl font-bold text-white mb-4">10. Data Breach Management</h2>
            <p class="text-[var(--text-secondary)] leading-relaxed mb-4">We maintain an incident response plan for data security events. In the event of a personal data breach, we will:</p>
            <ul class="list-disc pl-6 space-y-2 text-[var(--text-secondary)] leading-relaxed">
                <li>Contain and assess the scope and risk of the breach without delay.</li>
                <li>Notify affected individuals and the relevant supervisory authority where the breach is likely to result in risk to their rights and freedoms.</li>
                <li>Document the breach and the corrective actions taken.</li>
                <li>Review and strengthen safeguards to prevent recurrence.</li>
            </ul>
