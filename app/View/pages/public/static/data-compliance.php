            <h2 class="text-2xl font-bold text-white mb-4">4. Lawful Bases for Processing</h2>
            <p class="text-[var(--text-secondary)] leading-relaxed mb-4">Where required, each processing activity is grounded in at least one lawful basis:</p>
            <ul class="list-disc pl-6 space-y-2 text-[var(--text-secondary)] leading-relaxed">
                <li><strong class="text-white">Contract</strong> — performing orders, quotes, and agreed services.</li>
                <li><strong class="text-white">Legal obligation</strong> — tax, accounting, and regulatory record-keeping.</li>
                <li><strong class="text-white">Legitimate interests</strong> — security, fraud prevention, and service improvement, balanced against your rights.</li>
                <li><strong class="text-white">Consent</strong> — marketing and optional analytics, withdrawable at any time.</li>
            </ul>
        </div>

        <div>
            <h2 class="text-2xl font-bold text-white mb-4">5. Data Protection Principles</h2>
            <p class="text-[var(--text-secondary)] leading-relaxed mb-4">Our processing activities adhere to the core data protection principles:</p>
            <ul class="list-disc pl-6 space-y-2 text-[var(--text-secondary)] leading-relaxed">
                <li><strong class="text-white">Lawfulness, fairness, and transparency</strong> — we process data openly and as described in our policies.</li>
                <li><strong class="text-white">Purpose limitation</strong> — data is collected for specified, explicit, and legitimate purposes only.</li>
                <li><strong class="text-white">Data minimisation</strong> — we limit collection to what is relevant and necessary.</li>
                <li><strong class="text-white">Accuracy</strong> — we take reasonable steps to keep data accurate and up to date.</li>
                <li><strong class="text-white">Storage limitation</strong> — data is retained only as long as necessary.</li>
                <li><strong class="text-white">Integrity and confidentiality</strong> — data is protected with appropriate security measures.</li>
                <li><strong class="text-white">Accountability</strong> — we document and can demonstrate our compliance.</li>
            </ul>
        </div>

