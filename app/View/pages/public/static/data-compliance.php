                <li>Identity, contact, and company information of customers and prospects.</li>
                <li>Order, quotation, and transaction records.</li>
                <li>Account credentials and communication preferences.</li>
                <li>Technical usage data collected through cookies and analytics.</li>
                <li>Communications and support correspondence.</li>
            </ul>
